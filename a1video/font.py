def glyph_rows(rows7):
    """8 scan lines of 5-bit patterns (bit 4 = leftmost); scan line 0 blank."""
    out = [0]
    for r in rows7:
        out.append(sum(1 << (4 - i) for i, ch in enumerate(r) if ch == '#'))
    return out
